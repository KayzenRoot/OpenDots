# Start OpenDots automatically when this user logs in.
#
# Uses the per-user Startup folder, which needs no administrator rights.
# (A scheduled task would also work but Register-ScheduledTask requires
# elevation; the Startup folder does not.)
#
# Install:
#   powershell -ExecutionPolicy Bypass -File deployment\windows\install-autostart.ps1
#
# Remove:
#   Remove-Item "$env:APPDATA\Microsoft\Windows\Start Menu\Programs\Startup\OpenDots.vbs"
$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$start = Join-Path $repo 'deployment\windows\start.ps1'
if (-not (Test-Path $start)) { throw "start.ps1 not found at $start" }
$watchdog = Join-Path $repo 'deployment\windows\watchdog.ps1'

$startup = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Startup'
$target = Join-Path $startup 'OpenDots.vbs'

# A .vbs launcher runs PowerShell without a flashing console window.
$vbs = @"
' Starts the OpenDots local test stack at logon. Generated by install-autostart.ps1.
Set sh = CreateObject("WScript.Shell")
sh.Run "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File ""$start""", 0, False

' Health watchdog: restarts the stack if it stops answering /api/ready.
sh.Run "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File ""$watchdog""", 0, False
"@

Set-Content -Path $target -Value $vbs -Encoding ASCII
Write-Host "Installed autostart: $target" -ForegroundColor Green
Write-Host "It runs at logon. To start it now without logging out:"
Write-Host "  powershell -ExecutionPolicy Bypass -File `"$start`""
Write-Host ''
Write-Host "To remove it: Remove-Item `"$target`"" -ForegroundColor DarkGray
