# OpenDots one-click installer (no administrator rights required).
#
# It: checks Docker, creates .env.local with generated secrets if absent,
# builds and starts the stack, waits for readiness, installs autostart, and
# creates Desktop + Start Menu shortcuts that open the app in its own window.
$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
Set-Location $repo
$project = 'opendots'
$compose = @('-p', $project, '--env-file', '.env.local', '-f', 'compose.yml', '-f', 'compose.local.yml')

function Info($m) { Write-Host "[opendots] $m" -ForegroundColor Cyan }
function Fail($m) { Write-Host "[opendots] ERROR: $m" -ForegroundColor Red; exit 1 }

Info 'checking Docker'
$null = docker info 2>$null
if ($LASTEXITCODE -ne 0) {
    $dd = Join-Path $env:ProgramFiles 'Docker\Docker\Docker Desktop.exe'
    if (Test-Path $dd) {
        Info 'starting Docker Desktop'
        Start-Process $dd | Out-Null
        for ($i = 0; $i -lt 60; $i++) {
            Start-Sleep -Seconds 3
            $null = docker info 2>$null
            if ($LASTEXITCODE -eq 0) { break }
        }
    }
    $null = docker info 2>$null
    if ($LASTEXITCODE -ne 0) { Fail 'Docker is not running. Install/start Docker Desktop and run this again.' }
}

if (-not (Test-Path '.env.local')) {
    # A lost .env.local plus an existing database volume is unrecoverable: the new
    # generated password would not match the one baked into the volume. Fail with
    # an explanation instead of starting a stack that cannot authenticate.
    $volumes = docker volume ls --format '{{.Name}}' | Select-String 'opendots-pgdata'
    if ($volumes) {
        Fail ('A database volume already exists but .env.local is missing. ' +
              'The database password cannot be recovered. Restore .env.local from a backup, ' +
              'or remove the volume (docker volume rm ' + ($volumes | Select-Object -First 1).ToString().Trim() + ') to start over, which deletes all conversations.')
    }
    Info 'creating .env.local with generated secrets'
    if (-not (Test-Path '.env.example')) { Fail '.env.example not found; is this the OpenDots repository?' }

    function New-Secret([int]$bytes) {
        $b = New-Object byte[] $bytes
        [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
        [Convert]::ToBase64String($b).TrimEnd('=').Replace('+', 'A').Replace('/', 'B')
    }
    $dbPass = New-Secret 24
    $owner = New-Secret 24
    $modelKey = Read-Host 'Model provider API key (leave empty to fill in later)'
    $model = Read-Host 'Model name (leave empty for deepseek-v4.1-flash)'
    if ([string]::IsNullOrWhiteSpace($model)) { $model = 'deepseek-v4.1-flash' }
    $base = Read-Host 'Model base URL (leave empty for OpenCode Go)'
    if ([string]::IsNullOrWhiteSpace($base)) { $base = 'https://opencode.ai/zen/go/v1' }

    $env = @"
# Generated by install.ps1. Never commit this file.
DATABASE_URL=postgres://opendots:$dbPass@postgres:5432/opendots
POSTGRES_USER=opendots
POSTGRES_PASSWORD=$dbPass
POSTGRES_DB=opendots
OWNER_ID=opendots-owner
OWNER_TOKEN=$owner
APP_ORIGIN=http://localhost:4310,http://127.0.0.1:4310,http://localhost:8080,http://127.0.0.1:8080
OPENAI_BASE_URL=$base
OPENAI_API_KEY=$modelKey
OPENAI_MODEL=$model
OPENAI_EXTRA_HEADERS={'"x-opencode-session":"opendots-local"'}
WEB_SEARCH_PROVIDER=disabled
"@
    Set-Content -Path '.env.local' -Value $env -Encoding UTF8
    Write-Host ''
    Write-Host "Your access token (needed to unlock the app):" -ForegroundColor Yellow
    Write-Host "  $owner" -ForegroundColor Yellow
    Write-Host ''
}

$null = docker image inspect opendots-app 2>$null
if ($LASTEXITCODE -eq 0) {
    Info 'image already built; skipping build (delete the image to force a rebuild)'
} else {
    Info 'building (first run takes a few minutes)'
    docker compose @compose build
    if ($LASTEXITCODE -ne 0) { Fail 'image build failed' }
}

Info 'starting services'
docker compose @compose up -d
if ($LASTEXITCODE -ne 0) { Fail 'docker compose up failed' }

Info 'waiting for readiness'
$ready = $false
for ($i = 0; $i -lt 90; $i++) {
    try {
        $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 'http://127.0.0.1:8080/api/ready' -ErrorAction Stop
        if ($r.StatusCode -eq 200) { $ready = $true; break }
    } catch { Start-Sleep -Seconds 2 }
}
if (-not $ready) { Fail 'app did not become ready. Check: docker compose -p opendots logs app' }

Info 'installing autostart and shortcuts'
& (Join-Path $PSScriptRoot 'install-autostart.ps1') | Out-Null

$launcher = Join-Path $PSScriptRoot 'OpenDots.exe'
$desktop = [Environment]::GetFolderPath('Desktop')
$startMenu = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs'
if (Test-Path $launcher) {
    foreach ($dir in @($desktop, $startMenu)) {
        $lnk = Join-Path $dir 'OpenDots.lnk'
        $sh = New-Object -ComObject WScript.Shell
        $s = $sh.CreateShortcut($lnk)
        $s.TargetPath = $launcher
        $s.WorkingDirectory = $PSScriptRoot
        $s.IconLocation = "$launcher,0"
        $s.Description = 'OpenDots'
        $s.Save()
    }
    Info 'shortcuts created on Desktop and Start Menu'
}

Info 'opening OpenDots'
if (Test-Path $launcher) { Start-Process $launcher } else { Start-Process 'http://localhost:8080' }

Write-Host ''
Write-Host 'OpenDots installed.' -ForegroundColor Green
Write-Host '  App:      OpenDots (Desktop shortcut)'
Write-Host '  URL:      http://localhost:8080'
Write-Host '  Stop:     powershell -File deployment\windows\stop.ps1'
Write-Host '  Status:   powershell -File deployment\windows\status.ps1'
Write-Host '  Config:   .env.local'
